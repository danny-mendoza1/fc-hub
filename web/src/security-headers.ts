/**
 * Security and caching headers, in one place for both ways the UI is served:
 * - through the app (`withSecurityHeaders` in app.ts): every API response, and the whole UI on Node;
 * - straight from Cloudflare's asset server, which skips the Worker for UI files
 *   (`run_worker_first` in wrangler.toml), via the `_headers` file the build writes from
 *   {@link staticHeadersFile}. test/ui.test.ts checks the built file matches.
 */

/**
 * Strict CSP: only our own scripts/styles, no inline code, no framing, no third-party content.
 * Applied to every response (harmless on JSON) so the UI can't accidentally ship without it.
 */
export const CONTENT_SECURITY_POLICY = [
  "default-src 'none'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data:",
  "connect-src 'self'",
  "form-action 'self'",
  "base-uri 'none'",
  "frame-ancestors 'none'",
].join("; ");

/** Sent on every response. HSTS is separate: only over https. */
export const SECURITY_HEADERS: Readonly<Record<string, string>> = {
  "content-security-policy": CONTENT_SECURITY_POLICY,
  "x-content-type-options": "nosniff",
  "x-frame-options": "DENY",
  "referrer-policy": "no-referrer",
  "cross-origin-opener-policy": "same-origin",
  "permissions-policy": "camera=(), microphone=(), geolocation=(), interest-cohort=()",
};

export const HSTS = "max-age=31536000; includeSubDomains";

/** Vite's /assets/* files have content hashes in their names, so they never change. */
export const IMMUTABLE_ASSET = "public, max-age=31536000, immutable";

/**
 * API data is per-user and never cached. Hashed assets are cached forever; everything else
 * (index.html) is revalidated on each load so a deploy shows up immediately.
 */
export function cacheControl(pathname: string, status: number): string {
  // Icons never change for a given id; private because the route requires sign-in.
  if (pathname.startsWith("/api/v1/icons/") && status === 200) return "private, max-age=2592000, immutable";
  if (pathname.startsWith("/api/")) return "no-store";
  if (pathname.startsWith("/assets/") && status === 200) return IMMUTABLE_ASSET;
  return "no-cache";
}

/**
 * Cloudflare `_headers` for the UI files the asset server answers without the Worker. Same headers
 * as {@link cacheControl} and {@link SECURITY_HEADERS}. Rules that match a path all apply, so
 * `/assets/*` detaches the page's `no-cache` (`! Cache-Control`) before setting its own.
 */
export function staticHeadersFile(): string {
  const lines = ["# Generated by vite.config.ts from src/security-headers.ts. Do not edit.", "/*"];
  for (const [name, value] of Object.entries(SECURITY_HEADERS)) lines.push(`  ${name}: ${value}`);
  lines.push(
    `  strict-transport-security: ${HSTS}`,
    "  cache-control: no-cache",
    "/assets/*",
    "  ! cache-control",
    `  cache-control: ${IMMUTABLE_ASSET}`,
    "",
  );
  return lines.join("\n");
}
